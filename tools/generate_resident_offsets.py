#!/usr/bin/env python3
"""Generate absolute call addresses for the copied high-RAM VF3 resident shim."""
from __future__ import annotations
import argparse
import subprocess
from pathlib import Path

BASE = 0x8D000000
TEXT_END = 0x8D010000
WINDOW_END = 0x8D030000
FUNCTIONS = {
    "VF3_RESIDENT_ADDR_GD_INSTALL": "vf3_gd_install",
    "VF3_RESIDENT_ADDR_ORIGINAL_SERVICE": "vf3_gd_original_service",
    "VF3_RESIDENT_ADDR_LAST_DMA_STATUS": "vf3_gd_last_dma_status",
    "VF3_RESIDENT_ADDR_LAST_BYTES": "vf3_gd_last_bytes",
    "VF3_RESIDENT_ADDR_CHAINLOAD": "vf3_gd_chainload",
    "VF3_RESIDENT_ADDR_DIAG_PREPARE": "vf3_diag_prepare",
    "VF3_RESIDENT_ADDR_DIAG_BEGIN": "vf3_diag_begin",
}

def generate(nm: str, elf: Path, binary: Path) -> str:
    output = subprocess.check_output([nm, "-n", str(elf)], text=True)
    symbols = {}
    for line in output.splitlines():
        parts = line.split()
        if len(parts) < 3:
            continue
        try:
            address = int(parts[0], 16)
        except ValueError:
            continue
        symbols[parts[-1].lstrip("_")] = address
    lines = [
        "/* Generated by tools/generate_resident_offsets.py; do not edit. */",
        "#ifndef VF3_RESIDENT_OFFSETS_H",
        "#define VF3_RESIDENT_OFFSETS_H",
        f"#define VF3_RESIDENT_IMAGE_BASE 0x{BASE:08X}u",
        f"#define VF3_RESIDENT_IMAGE_SIZE {binary.stat().st_size}u",
    ]
    for macro, name in FUNCTIONS.items():
        if name not in symbols:
            raise ValueError(f"resident ELF is missing symbol {name}")
        address = symbols[name]
        if not BASE <= address < TEXT_END:
            raise ValueError(f"{name} is outside resident text: 0x{address:08X}")
        lines.append(f"#define {macro} 0x{address:08X}u")
    if binary.stat().st_size <= 0x20000 or binary.stat().st_size > WINDOW_END - BASE:
        raise ValueError(f"unexpected resident image size: {binary.stat().st_size}")
    lines += ["#endif", ""]
    return "\n".join(lines)

def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--nm", required=True)
    parser.add_argument("--elf", type=Path, required=True)
    parser.add_argument("--bin", type=Path, required=True)
    parser.add_argument("--output", type=Path, required=True)
    args = parser.parse_args()
    text = generate(args.nm, args.elf, args.bin)
    args.output.write_text(text, encoding="utf-8")
    print(f"Generated {args.output}: {args.bin.stat().st_size} resident bytes")

if __name__ == "__main__":
    main()
