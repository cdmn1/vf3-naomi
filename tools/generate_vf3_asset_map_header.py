#!/usr/bin/env python3
"""Generate the SH-4 runtime FAD lookup table from a packed VF3 asset map."""
from __future__ import annotations
import argparse, json
from pathlib import Path

SECTOR = 2048

def generate(map_path: Path, payload_base: int) -> str:
    doc = json.loads(map_path.read_text(encoding="utf-8"))
    if doc.get("format") != "VF3NAOMI_PACKED_ASSETS_V1":
        raise ValueError("unsupported packed asset map format")
    if doc.get("sector_bytes") != SECTOR:
        raise ValueError("unexpected sector size")
    if payload_base < 0 or payload_base % SECTOR:
        raise ValueError("payload base must be a non-negative 2048-byte boundary")
    entries = sorted(doc.get("entries", []), key=lambda x: x["fad"])
    test_asset = next((e for e in entries if e["name"].upper() == "1ST_READ.BIN"), None)
    if test_asset is None:
        raise ValueError("1ST_READ.BIN is required as the runtime mapping smoke-test asset")
    previous_end = -1
    for e in entries:
        fad, sectors, offset = int(e["fad"]), int(e["sectors"]), int(e["payload_offset"])
        if fad < 0 or sectors <= 0 or offset < 0 or offset % SECTOR:
            raise ValueError(f"invalid mapping entry: {e.get('name')}")
        if fad < previous_end:
            raise ValueError(f"overlapping FAD range at {e.get('name')}")
        previous_end = fad + sectors
    lines = [
        "/* Generated by tools/generate_vf3_asset_map_header.py; do not edit. */",
        "#ifndef VF3_ASSET_MAP_H", "#define VF3_ASSET_MAP_H",
        "#include <stdint.h>",
        "typedef struct { uint32_t fad_start, sectors, payload_offset; } vf3_asset_range;",
        f"#define VF3_ASSET_MAP_COUNT {len(entries)}u",
        f"#define VF3_ASSET_PAYLOAD_BASE {payload_base}u",
        f"#define VF3_ASSET_TEST_FAD {int(test_asset['fad'])}u",
        f"#define VF3_ASSET_TEST_OFFSET {payload_base + int(test_asset['payload_offset'])}u",
        "static const vf3_asset_range vf3_asset_map[VF3_ASSET_MAP_COUNT ? VF3_ASSET_MAP_COUNT : 1] __attribute__((section(\".vf3_resident_rodata\"), used)) = {",
    ]
    for e in entries:
        absolute = payload_base + int(e["payload_offset"])
        if absolute > 0xffffffff:
            raise ValueError("payload offset exceeds 32-bit cartridge addressing")
        lines.append(f"    {{{int(e['fad'])}u, {int(e['sectors'])}u, {int(e['payload_offset'])}u}}, /* {e['name']} */")
    lines += ["};", "#endif", ""]
    return "\n".join(lines)

def main():
    p=argparse.ArgumentParser(description=__doc__)
    p.add_argument("--map-json", type=Path, required=True)
    p.add_argument("--payload-base", type=lambda x:int(x,0), required=True)
    p.add_argument("--output", type=Path, required=True)
    a=p.parse_args()
    text=generate(a.map_json,a.payload_base)
    a.output.parent.mkdir(parents=True,exist_ok=True)
    a.output.write_text(text,encoding="utf-8")
    print(f"Generated {a.output}: {text.count('}, /* ')} FAD ranges, payload base 0x{a.payload_base:08X}")

if __name__ == "__main__":
    main()
